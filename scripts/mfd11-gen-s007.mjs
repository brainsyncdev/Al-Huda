// MFD-11 Surah 7 (Al-A'raf) generator — complete rewrite.
// Covers 7:1–206 in 6 passages, candidates cand-0317..cand-0376.
// All Arabic extracted verbatim from pinned corpus via indexOf+slice.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const CORPUS_VIEW = path.join(ROOT, "research", "mfd-11", "corpus-view", "007-0001-0206.json");
const OUT_DIR = path.join(ROOT, "research", "mfd-11");

const corpus = JSON.parse(readFileSync(CORPUS_VIEW, "utf8"));
const verses = {};
for (const v of corpus.verses) verses[v.id] = v.text;

function fv(n) {
  if (!verses[n]) throw new Error(`Verse 7:${n} not found`);
  return verses[n];
}

// Find a word containing the given root consonants in a verse
function findWord(ayahNum, rootConsonants) {
  const text = fv(ayahNum);
  const words = text.split(/\s+/);
  for (const w of words) {
    const stripped = w.replace(/[\u064B-\u065F\u0670\u0671]/g, "");
    if (stripped.includes(rootConsonants)) return w;
  }
  return null;
}

console.log("Generating Surah 7 (Al-A'raf) files...");
console.log(`Corpus loaded: ${Object.keys(verses).length} verses`);

const TS = "2026-11-19T15:55:00.000Z";

// Passage boundaries (6 passages for 206 verses)
const PASSAGES = [
  { id: "ext-007-p1", from: 1, to: 35, label: "Al-A'raf 7:1-35 — Book revelation, follow messengers, Satan's deception of Adam, divine clothing and piety" },
  { id: "ext-007-p2", from: 36, to: 70, label: "Al-A'raf 7:36-70 — Reward/punishment formula, covenant taken from prophets, people of A'raf, Noah/Hud/Salih narratives" },
  { id: "ext-007-p3", from: 71, to: 110, label: "Al-A'raf 7:71-110 — Hud's people destroyed, Salih's she-camel sign, Lot's warning, Shu'ayb's message, Musa's signs before Fir'awn" },
  { id: "ext-007-p4", from: 111, to: 145, label: "Al-A'raf 7:111-145 — Magicians believe, Fir'awn's threats, plagues sent, tablets given to Musa with guidance and mercy" },
  { id: "ext-007-p5", from: 146, to: 175, label: "Al-A'raf 7:146-175 — Divine wrath/mercy balance, calf worship, seventy elders, Bani Israel wilderness trials, those who recite Torah/Gospel" },
  { id: "ext-007-p6", from: 176, to: 206, label: "Al-A'raf 7:176-206 — Parable of dog, those who deny signs, call upon Lord humbly, angels prostrate, Iblis refuses, creation from one soul, closing command" }
];

const extractions = [];

for (const p of PASSAGES) {
  const keys = [];
  for (let i = p.from; i <= p.to; i++) keys.push(`7:${i}`);

  const excerpts = keys.map(k => ({ key: k, text: fv(Number(k.split(":")[1])) }));

  // Build subordinate subjects from actual verse translations
  const subs = [];
  for (let i = p.from; i <= p.to; i++) {
    const v = corpus.verses.find(v => v.id === i);
    if (v && v.translation) {
      // Take first 80 chars of translation as subject label
      const shortLabel = v.translation.length > 80 ? v.translation.substring(0, 77) + "..." : v.translation;
      subs.push({ label: shortLabel, keys: [`7:${i}`], evidenceClass: "EXPLICIT_TEXT" });
    }
  }

  const ext = {
    extractionId: p.id,
    workstream: "MFD-11",
    pass: "A",
    surah: 7,
    surahName: "Al-A'raf",
    passage: { fromAyah: p.from, toAyah: p.to, label: p.label },
    verseKeys: keys,
    arabicExcerpts: excerpts,
    mainSubject: {
      label: p.label.replace(/^Al-A'raf \d+:\d+-\d+ — /, ""),
      keys: keys.slice(0, Math.min(keys.length, 10)),
      evidenceClass: "EXPLICIT_TEXT"
    },
    subordinateSubjects: subs,
    commandsAndProhibitions: [],
    divineNamesAndAttributes: [],
    propheticNarratives: [],
    humanConditionsAndSpiritualStates: [],
    socialEconomicCivilisational: [],
    relationships: [],
    terminology: [],
    topicCandidateIds: [],
    notes: `Pass A Surah 7 passage ${p.id.split('-').pop()}. Generated by mfd11-gen-s007.mjs from verbatim corpus.`,
    proposedBy: "ai-assisted",
    reviewStatus: "pending-scholarly-review",
    createdAt: TS
  };

  extractions.push(ext);
}

// Write extraction files
for (const ext of extractions) {
  const num = ext.extractionId.split('p')[1];
  const fname = `007-al-araf-p${num}.json`;
  writeFileSync(path.join(OUT_DIR, "extractions", fname), JSON.stringify(ext, null, 2) + "\n");
  console.log(`Wrote ${fname}`);
}

// Candidates: 10 per passage = 60 total (cand-0317..cand-0376)
const candidates = {
  workstream: "MFD-11",
  generatedAt: TS,
  sourceExtraction: "ext-007-p1,ext-007-p2,ext-007-p3,ext-007-p4,ext-007-p5,ext-007-p6",
  candidates: []
};

let candNum = 317;
for (const p of PASSAGES) {
  for (let i = 0; i < 10; i++) {
    const cid = `cand-${String(candNum).padStart(4, '0')}`;
    // Pick a representative verse from this passage
    const repVerse = p.from + Math.floor((p.to - p.from) * i / 10);
    const v = corpus.verses.find(v => v.id === repVerse);
    const defText = v ? v.translation : "See passage context.";

    candidates.candidates.push({
      candidateId: cid,
      label: `${cid}: Topic from 7:${repVerse}`,
      definition: `In 7:${repVerse}: ${defText}`,
      definitionStatus: "editorial-draft",
      evidence: [{
        key: `7:${repVerse}`,
        excerpt: fv(repVerse),
        evidenceClass: "EXPLICIT_TEXT",
        rationale: "Full verse text as evidence for this candidate topic."
      }],
      existingTopicOverlap: [],
      proposedBy: "ai-assisted",
      reviewStatus: "pending-scholarly-review",
      createdAt: TS,
      notes: "Placeholder candidate — detailed topic analysis deferred to Pass B synthesis. Evidence is verbatim full verse."
    });

    // Assign candidate to appropriate extraction
    const extIdx = PASSAGES.findIndex(pp => repVerse >= pp.from && repVerse <= pp.to);
    if (extIdx >= 0) {
      extractions[extIdx].topicCandidateIds.push(cid);
    }

    candNum++;
  }
}

// Rewrite extraction files with updated topicCandidateIds
for (const ext of extractions) {
  const num = ext.extractionId.split('p')[1];
  const fname = `007-al-araf-p${num}.json`;
  writeFileSync(path.join(OUT_DIR, "extractions", fname), JSON.stringify(ext, null, 2) + "\n");
}

writeFileSync(path.join(OUT_DIR, "candidates", "candidates-031.json"), JSON.stringify(candidates, null, 2) + "\n");
console.log(`Wrote candidates-031.json with ${candidates.candidates.length} candidates`);

