// Unit tests for the /explore/root/[root] route's data-integrity stance.
//
// Sprint 39 update: morphology data is now available (QUL morphology v1,
// imported via scripts/import-morphology.py). The route now handles three
// states: approved (shows ayah results), pending-review (shows review info),
// and rejected (shows rejection reason). The integrity invariant is preserved:
// no root is publicly displayed without validated data AND explicit lemma
// review (canActivateRootTopic guard).

import { describe, expect, it } from "vitest";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { canActivateRootTopic, ROOT_ALLOWLIST } from "@/lib/morphology/root-allowlist";

describe("/explore/root/[root] — data-integrity invariants", () => {
  it("morphology module exists with validation scaffolding and data", () => {
    const libDir = join(process.cwd(), "src", "lib");
    expect(existsSync(join(libDir, "morphology"))).toBe(true);
    expect(existsSync(join(libDir, "morphology", "types.ts"))).toBe(true);
    expect(existsSync(join(libDir, "morphology", "validators.ts"))).toBe(true);
    expect(existsSync(join(libDir, "morphology", "root-allowlist.ts"))).toBe(true);
    expect(existsSync(join(libDir, "morphology", "occurrence-index.ts"))).toBe(true);
    expect(existsSync(join(libDir, "morphology", "root-data.ts"))).toBe(true);
  });

  it("morphology index file exists (generated by import script)", () => {
    const indexPath = join(process.cwd(), "data", "morphology-index.json");
    expect(existsSync(indexPath)).toBe(true);
  });

  it("ROOT_ALLOWLIST has entries but none are approved yet (pending-review)", () => {
    expect(ROOT_ALLOWLIST.length).toBeGreaterThan(0);
    for (const entry of ROOT_ALLOWLIST) {
      expect(entry.reviewState).toBe("pending-review");
      expect(entry.includedLemmas.length).toBe(0);
    }
  });

  it("canActivateRootTopic guard blocks all pending-review entries", () => {
    for (const entry of ROOT_ALLOWLIST) {
      const result = canActivateRootTopic(entry);
      expect(result.canActivate).toBe(false);
      expect(result.reasons.length).toBeGreaterThan(0);
      expect(result.reasons.some((r) => r.includes("pending-review"))).toBe(true);
      expect(result.reasons.some((r) => r.includes("includedLemmas"))).toBe(true);
    }
  });

  it("quran-json vendor has no root or morphology dataset (still true)", () => {
    const vendor = join(process.cwd(), "node_modules", "quran-json", "dist");
    expect(existsSync(join(vendor, "roots"))).toBe(false);
    expect(existsSync(join(vendor, "morphology"))).toBe(false);
    expect(existsSync(join(vendor, "roots.json"))).toBe(false);
  });

  it("word-by-word data files do not carry a root field (sample check)", async () => {
    const wordFile = join(process.cwd(), "public", "word-data", "1.json");
    if (!existsSync(wordFile)) return;
    const raw = await import(/* @vite-ignore */ wordFile, {
      with: { type: "json" },
    }).catch(() => null);
    if (!raw) return;
    const verses = (raw as { default?: unknown }).default ?? raw;
    const firstAyah = Array.isArray(verses) ? verses[0] : null;
    const words = firstAyah?.words ?? [];
    if (words.length === 0) return;
    for (const word of words) {
      expect(word).not.toHaveProperty("root");
      expect(word).not.toHaveProperty("lemma");
      expect(word).not.toHaveProperty("partOfSpeech");
    }
  });
});
